-- Réplique de l'état actuel de ta base (d'après le diagnostic + le script de protection)
drop database if exists bpe; create database bpe;
\c bpe
do $$ begin create role anon nologin; exception when duplicate_object then null; end $$;
do $$ begin create role authenticated nologin; exception when duplicate_object then null; end $$;
create table public.scores (id bigint generated by default as identity primary key, created_at timestamptz default now(), pseudo text, hero text, score integer, joueur_id uuid);
alter table public.scores enable row level security;
create policy "ajout seulement" on public.scores for insert to anon, authenticated with check (true);
create view public.classement as select distinct on (lower(pseudo)) pseudo, hero, score, created_at from public.scores order by lower(pseudo), score desc, created_at;
grant usage on schema public to anon, authenticated;
grant insert (pseudo, hero, score, joueur_id) on public.scores to anon, authenticated;
grant select on public.classement to anon, authenticated;
alter table public.scores add constraint scores_valeurs check (coalesce(score between 0 and 10000 and hero in ('francois','gabriel','hugues','samuel') and char_length(pseudo) between 1 and 20 and pseudo !~ '[[:cntrl:]]' and joueur_id is not null, false)) not valid;
create or replace function public.scores_avant_ajout() returns trigger language plpgsql security definer set search_path = public as $$
declare proprio uuid;
begin
  new.pseudo := btrim(new.pseudo); new.created_at := now();
  if new.joueur_id is null then raise exception 'Joueur inconnu'; end if;
  select joueur_id into proprio from public.scores where lower(pseudo) = lower(new.pseudo) order by created_at limit 1;
  if proprio is not null and proprio <> new.joueur_id then raise exception 'Ce pseudo est déjà pris par un autre joueur'; end if;
  if exists (select 1 from public.scores where joueur_id = new.joueur_id and created_at > now() - interval '2 minutes') then raise exception 'Trop d''envois rapprochés, réessayez plus tard'; end if;
  return new;
end $$;
create trigger scores_avant_ajout before insert on public.scores for each row execute function public.scores_avant_ajout();
insert into public.scores (pseudo, hero, score, joueur_id) values ('Ancien', 'gabriel', 7000, gen_random_uuid());
create or replace function public.reserver_pseudo(p text, j uuid)
returns text language sql stable security definer set search_path = public as $$
  select coalesce((select case when joueur_id = j then 'ok' else 'pris' end from public.scores
                    where lower(pseudo) = lower(btrim(p)) order by created_at limit 1), 'ok');
$$;
revoke all on function public.reserver_pseudo(text, uuid) from public;
grant execute on function public.reserver_pseudo(text, uuid) to anon, authenticated;
